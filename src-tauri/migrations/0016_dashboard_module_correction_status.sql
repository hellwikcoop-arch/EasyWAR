-- Стан виправлення, внесеного на екрані «Перевірка» під час підтягування з таблиці.
-- Первинне виправлення (сирий текст, введений текст, місце в XLSX) лишається незмінним
-- фактом імпорту; тут — чи воно досі пояснює поточне значення запису.
--
-- `stored_value` — канонічне значення, яке записано в SQLite після виправлення, як JSON
-- (`"14:25"`, `300`, `true`): «300 м» у `corrected_text` стає числом 300, тож порівнювати
-- тексти не можна. Для виправлень, створених до цієї міграції, — NULL: поточність таких
-- виправлень не підтверджена, доки поле не змінять.
-- `superseded_at` — коли ручна правка в модулі змінила саме це поле запису (виправлення
-- стало історією імпорту). NULL — значення не змінювали.
ALTER TABLE dashboard_module_corrections
    ADD COLUMN stored_value TEXT CHECK (stored_value IS NULL OR length(stored_value) <= 8192);

ALTER TABLE dashboard_module_corrections
    ADD COLUMN superseded_at TEXT;
