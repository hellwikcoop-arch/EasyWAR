// Ключі з тексту таблиці. Розпізнавання збігається з carrierKey/munKey у air.html: тут воно ще знає Mirage і Су-25.
export function aircraftId(text) {
  const s = String(text || '').toUpperCase().replace(/[\s\-–—_.]/g, '');
  if (/^[MМ][IІ][GГ]29/.test(s)) return 'mig29';
  if (/^F16/.test(s)) return 'f16';
  if (/^[SСC][UУY]27/.test(s)) return 'su27';
  if (/^[SСC][UУY]25/.test(s)) return 'su25';
  if (/^[SСC][UУY]24/.test(s)) return 'su24';
  if (/^[MМ][IІ]24/.test(s)) return 'mi24';
  if (/^[MМ][IІ]8/.test(s)) return 'mi8';
  if (/^(JAS39|GRIPEN|ГРИПЕН)/.test(s)) return 'gripen';
  if (/^(MIRAGE|МІРАЖ|МИРАЖ|M2000)/.test(s)) return 'mirage';
  return '';
}

export function munitionId(text) {
  const s = String(text || '').toUpperCase();
  if (/HAMMER|AASM/.test(s)) return 'aasm';
  if (/STORM\s*SHADOW|SCALP/.test(s)) return 'storm';
  if (/GMLRS|(^|[^A-Z0-9])M\s*-?\s*31(\D|$)/.test(s)) return 'gmlrs';
  if (/ATACMS|MGM\D*140/.test(s)) return 'atacms';
  if (/AGM\D*88|HARM/.test(s)) return 'agm88';
  if (/AGM\D*65|MAVERICK|МАВЕРІК|МАВЕРИК/.test(s)) return 'agm65';
  if (/AIM\D*120|AMRAAM|АМРААМ/.test(s)) return 'aim120';
  if (/AIM\D*9|SIDEWINDER|САЙДВІНДЕР|САЙДВИНДЕР/.test(s)) return 'aim9';
  if (/(^|[^A-ZА-ЯІЇЄҐ0-9])[RР]\s*-?\s*27(\D|$)/.test(s)) return 'r27';
  if (/(^|[^A-ZА-ЯІЇЄҐ0-9])[RР]\s*-?\s*77(\D|$)|РВВ\s*-?\s*АЕ/.test(s)) return 'r77';
  if (/(^|[^A-ZА-ЯІЇЄҐ0-9])(KH|Х|X)\s*-?\s*29(\D|$)/.test(s)) return 'kh29';
  if (/(KAB|КАБ)\s*-?\s*500/.test(s)) return 'kab500';
  if (/BLU\D*140/.test(s)) return 'blu140';
  if (/(^|[^A-ZА-ЯІЇЄҐ0-9])[CСS]\s*-?\s*13(\D|$)/.test(s)) return 'c13';
  const d = /GBU\D*(\d+)/.exec(s);
  return d ? d[1] : '';
}

const fold = t => String(t || '').toLowerCase().replace(/[\s\-–—_./]+/g, '');

// Пошук у назві, псевдонімі, ролі й ключових словах; порожній запит повертає все. group — 'aircraft' | 'munition' | 'ground' | ''.
export function searchEntries(query, group = '') {
  const q = fold(query);
  return ENTRIES.filter(e => (!group || e.group === group)
    && (!q || fold([e.name, e.alias, e.role, e.origin, ...e.tags].join(' ')).includes(q)));
}

// Підсумок по завантаженій таблиці вильотів для статті: скільки вильотів і БП, результати, період і найчастіші пари.
export function usageFor(rows, entry) {
  const air = entry.group === 'aircraft';
  const own = rows.filter(r => (air ? aircraftId(r.aircraft) : munitionId(r.munition)) === entry.id);
  if (!own.length) return { flights: 0, used: 0, results: { hit: 0, part: 0, miss: 0, unk: 0 }, from: '', to: '', partners: [] };
  const results = { hit: 0, part: 0, miss: 0, unk: 0 }, partners = new Map();
  let used = 0, from = '', to = '';
  for (const r of own) {
    used += r.count || 0;
    results[r.kind in results ? r.kind : 'unk']++;
    if (r.date && (!from || r.date < from)) from = r.date;
    if (r.date && (!to || r.date > to)) to = r.date;
    const other = air ? r.munition : r.aircraft, id = air ? munitionId(other) : aircraftId(other);
    const key = id || String(other || '').trim();
    if (key) partners.set(key, { id, label: String(other || '').trim(), n: (partners.get(key)?.n || 0) + 1 });
  }
  return { flights: own.length, used, results, from, to, partners: [...partners.values()].sort((a, b) => b.n - a.n).slice(0, 6) };
}
