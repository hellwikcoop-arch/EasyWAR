function finish(entry, d, n) {
  const live = [];
  if (d.value) live.push(`Зараз на екрані: ${clip(d.value, 60)}`);
  const hint = d.hint ? clip(d.hint) : '';
  return {
    status: 'found',
    id: entry.id,
    title: clip(entry.title || d.label || d.panelTitle, 80),
    what: entry.what,
    basis: entry.basis,
    live: live[0] || null,
    hint: hint && !entry.what.includes(hint) ? hint : null,
    sources: entry.sources,
    origin: 'explain',
  };
}

// Головна функція ядра. Дескриптор: { branch, kind, label, group, panelTitle, value, hint }.
// Результат, окрім тексту пояснення, має `ref` — { id, title } зі статичного каталогу
// (assistant-explain-refs-core.js). Лише його пакет пропозиції розробнику бере як «Елемент»:
// `title`, `live` і `hint` походять з екрана й можуть містити текст таблиці.
export function explainElement(descriptor = {}) {
  const result = describeElement(descriptor);
  return { ...result, ref: explainRef(result) };
}

function describeElement(descriptor) {
  const d = {
    branch: ['air', 'rocket', 'dshv'].includes(descriptor.branch) ? descriptor.branch : 'other',
    part: clip(descriptor.part, 40),
    scope: descriptor.scope === 'own' ? 'own' : '',
    kind: typeof descriptor.kind === 'string' ? descriptor.kind : 'other',
    label: clip(descriptor.label, 80),
    group: normalizeLabel(descriptor.group),
    panelTitle: clip(descriptor.panelTitle, 80),
    value: clip(descriptor.value, 60),
    hint: clip(descriptor.hint),
  };
  const n = nouns(d.branch);
  const label = normalizeLabel(d.label);
  const panel = normalizeLabel(d.panelTitle);
  // Правила описують лише дашборди ПС і РВ. Для інших модулів не вгадуємо: лише екран і пошук у довідці.
  if (d.branch === 'other') return unknown(d);
  // Дашборд УДШВ має власну розмітку й власні правила: пояснення живуть в окремому ядрі.
  if (d.branch === 'dshv') {
    const entry = explainUdshv(d);
    return entry ? finish(entry, d, n) : unknown(d);
  }

  // Вкладка називається так само, як показник («Вильоти», «Ефективність»), тому її розбираємо першою.
  if (d.kind === 'tab') {
    if (!VIEW_TABS.has(label)) return unknown(d);
    return finish({ id: 'view-tab', title: `Вкладка «${d.label}»`, what: VIEW_TABS.get(label), basis: ['Вкладки та розрізи описані в довідці. У режимі пояснення вкладка не відкривалась.'], sources: [SRC.tabs] }, d, n);
  }
  for (const entry of ENTRIES) {
    if (entry.match(label, d)) return finish({ id: entry.id, ...entry.build(d, n) }, d, n);
  }
  if (DIMENSIONS.has(label) && (d.group === 'розріз даних' || d.kind === 'control')) {
    return finish({ id: 'dimension', title: `Розріз «${d.label}»`, what: 'Спосіб групування записів у таблиці розрізу.', basis: ['Запис без значення потрапляє до групи «Не вказано»; запис із кількома типами цілей входить до кожного з них.', 'У режимі пояснення розріз не змінено.'], sources: [SRC.tabs] }, d, n);
  }
  if (d.group === 'швидкий вибір періоду') {
    return finish({ id: 'preset', title: 'Швидкий вибір періоду', what: 'Задає межі періоду, за який рахуються всі показники.', basis: ['Усі лічильники, ефективність і зміни порівняння перераховуються для вибраного періоду. У режимі пояснення період не змінено.'], sources: [SRC.counters] }, d, n);
  }
  const panelBuilder = PANELS.get(label) || PANELS.get(panel);
  if (panelBuilder) {
    const built = panelBuilder(n);
    const title = PANELS.has(label) ? d.label : d.panelTitle;
    return finish({ id: 'panel', title, ...built }, d, n);
  }
  return unknown(d);
}

function unknown(d) {
  return {
    status: 'unknown',
    id: 'unknown',
    title: clip(d.label || d.panelTitle || 'Елемент', 80),
    what: EXPLAIN_UNKNOWN,
    basis: [],
    live: d.value ? `Зараз на екрані: ${d.value}` : null,
    hint: d.hint || null,
    sources: [],
    origin: 'explain',
  };
}
