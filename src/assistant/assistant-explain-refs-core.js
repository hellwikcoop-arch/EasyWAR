/** Назва за ідентифікатором із каталогу; для будь-якого іншого значення — порожній рядок. */
export function explainRefTitle(id) {
  return typeof id === 'string' && Object.prototype.hasOwnProperty.call(EXPLAIN_REFS, id) ? EXPLAIN_REFS[id] : '';
}

/**
 * Посилання на пояснення для пакета пропозиції: { id, title }.
 * Береться лише `result.status` і `result.id`; будь-які тексти результату (title, live, hint) ігноруються.
 */
export function explainRef(result) {
  const id = result?.status === 'found' && explainRefTitle(result.id) ? result.id : EXPLAIN_REF_NONE;
  return Object.freeze({ id, title: EXPLAIN_REFS[id] });
}
