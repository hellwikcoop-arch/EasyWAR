// Колеса як окремі тіла: [{ x, y, z, r, hw, steer, axle }] — для розрізання мешів і керування.
export function wheelsOf(spec) {
  const out = [];
  spec.axles.forEach((x, axle) => {
    for (const side of [-1, 1]) out.push({ x, y: spec.y, z: side * spec.z, r: spec.r, hw: .45, steer: spec.steer.includes(x), axle, side });
  });
  return out;
}

// Передня й задня групи осей для нахилу корпуса за рельєфом: передні — ті, що попереду середини бази.
export function axleGroups(axles) {
  const mid = axles.reduce((s, x) => s + x, 0) / axles.length;
  const front = axles.filter(x => x > mid), rear = axles.filter(x => x <= mid);
  const avg = list => list.reduce((s, x) => s + x, 0) / list.length;
  return { front: avg(front.length ? front : axles), rear: avg(rear.length ? rear : axles) };
}

