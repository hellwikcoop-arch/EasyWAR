// Труби пакета: [x, y, z] кожної, рядами зверху вниз; номер труби — ряд · кількість стовпців + стовпець.
export function tubeGrid(x, rows, cols) {
  return rows.flatMap(y => cols.map(z => [x, y, z]));
}

// Порядок пусків залпу: пара з країв, потім середина — так пакет не перевантажує один бік. Для 12 труб таблиця з артефакту автора
// моделей, для іншої кількості крок, взаємно простий з n.
export function ordFor(n) {
  if (n <= 2) return [...Array(Math.max(0, n)).keys()];
  if (n === 12) return [0, 3, 1, 2, 4, 7, 5, 6, 8, 11, 9, 10];
  const gcd = (a, b) => (b ? gcd(b, a % b) : a);
  const step = [7, 5, 3].find(s => gcd(n, s) === 1) || 1;
  return [...Array(n).keys()].map(i => (i * step) % n);
}

// Кінці гідроциліндрів підйому для кута підйому pitch і повороту yaw (радіани): a — на шасі, b — на пакеті; метри системи моделі.
// att задано в системі шарніра для пакета в похідному положенні, тож точка спершу повертається на кут підйому, потім разом з усім
// пакетом — навколо вертикалі через шарнір.
export function liftEnds(spec, pitch, yaw) {
  const [px, py] = spec.pivot, { anchor, att, z } = spec.lifts;
  const c = Math.cos(pitch), s = Math.sin(pitch), cy = Math.cos(yaw), sy = Math.sin(yaw);
  return [-1, 1].map(side => {
    const zz = side * z, bx = att[0] * c - att[1] * s, by = att[0] * s + att[1] * c;
    return { a: [anchor[0], anchor[1], zz], b: [px + bx * cy + zz * sy, py + by, -bx * sy + zz * cy] };
  });
}

