const BY_ID = new Map(ENTRIES.map(e => [e.id, e]));
export const variantsOf = entry => (entry.variants && entry.variants.length > 1 ? entry.variants : []);
const variantFor = (entry, id) => variantsOf(entry).find(v => v.id === id) || variantsOf(entry)[0] || entry;
export const modelOf = (entry, variantId) => variantFor(entry, variantId).model;
export const creditOf = (entry, variantId) => variantFor(entry, variantId).credit;
export const entryById = id => BY_ID.get(id) || null;

const fold = t => String(t || '').toLowerCase().replace(/[\s\-–—_./]+/g, '');

/** Пошук у назві, псевдонімі, ролі й ключових словах; extra(entry) додає текст (наприклад, підписи рядків таблиці). */
export function searchEntries(query, group = '', extra = null) {
  const q = fold(query);
  return ENTRIES.filter(e => (!group || e.group === group)
    && (!q || fold([e.name, e.alias, e.role, e.origin, ...e.tags, extra ? extra(e) : ''].join(' ')).includes(q)));
}

/** Статті, групи таблиці яких описано явно, у порядку ENTRIES; решта груп належить статті з tableGroups === REST. */
export function entryForGroup(group, entries = ENTRIES) {
  const own = entries.find(e => Array.isArray(e.tableGroups) && e.tableGroups.includes(group));
  return own || entries.find(e => e.tableGroups === REST) || null;
}

/** Групи таблиці, що належать статті (для REST — усі, яких не описано в інших статтях). */
export function groupsOf(entry, allGroups, entries = ENTRIES) {
  if (entry.tableGroups === REST) return allGroups.filter(g => entryForGroup(g, entries)?.id === entry.id);
  return allGroups.filter(g => (entry.tableGroups || []).includes(g));
}
